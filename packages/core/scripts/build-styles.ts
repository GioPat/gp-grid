// packages/core/scripts/build-styles.ts
// Bundles src/styles/index.css with Lightning CSS. tsdown.config.ts writes the
// result to dist/styles.css; this script also writes the always-minified copy
// to the git-ignored src/styles/grid-styles.ts as `gridStyles`, regenerated at
// the same points as sort-worker-code.ts (install, build, test, `pnpm build:styles`).

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bundle } from "lightningcss";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const STYLES_ENTRY = resolve(packageRoot, "src/styles/index.css");
const STYLES_MODULE = resolve(packageRoot, "src/styles/grid-styles.ts");

export const bundleStyles = (minify: boolean): string =>
  bundle({ filename: STYLES_ENTRY, minify }).code.toString();

export const renderStylesModule = (css: string): string =>
  [
    "// packages/core/src/styles/grid-styles.ts",
    "// GENERATED by scripts/build-styles.ts from src/styles/*.css — do not edit.",
    "",
    "/** The grid stylesheet as a string, for hosts that only accept CSS-in-JS or need it in a shadow root. */",
    `export const gridStyles: string = ${JSON.stringify(css)};`,
    "",
  ].join("\n");

/** Regenerate grid-styles.ts. Returns true when the file changed. */
export const writeStylesModule = (): boolean => {
  const next = renderStylesModule(bundleStyles(true));
  const previous = existsSync(STYLES_MODULE) ? readFileSync(STYLES_MODULE, "utf8") : "";
  if (previous === next) return false;
  writeFileSync(STYLES_MODULE, next);
  return true;
};

if (import.meta.main) {
  console.log(writeStylesModule() ? "✓ grid-styles.ts regenerated" : "✓ grid-styles.ts up to date");
}
